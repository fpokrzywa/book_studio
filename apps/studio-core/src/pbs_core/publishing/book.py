@dataclass
class BookAsset:
    short_hash: str
    mime: str
    data: bytes
    width_px: int | None
    height_px: int | None
    name: str

    @property
    def ext(self) -> str:
        return {"image/png": "png", "image/jpeg": "jpg", "image/gif": "gif", "image/webp": "webp"}.get(self.mime, "bin")


@dataclass
class BookChapter:
    id: str
    title: str
    slug: str
    kind: str
    depth: int
    number: int | None  # chapter number (top-level chapters only)
    source_md: str
    doc: dict[str, Any] | None
    revision_no: int


@dataclass
class MatterItem:
    kind: str
    position: str
    title: str
    body_md: str
    generated: bool
    doc: dict[str, Any] | None = None


@dataclass
class BibEntry:
    key: str
    authors: list[str]
    year: str | None
    title: str
    publisher: str | None
    url: str | None
    doi: str | None


@dataclass
class Book:
    project_id: str
    title: str
    subtitle: str | None
    author: str | None
    language: str
    template_key: str
    template: dict[str, Any]
    front: list[MatterItem]
    chapters: list[BookChapter]
    back: list[MatterItem]
    copyright: dict[str, Any]
    bibliography: dict[str, BibEntry]
    cited_keys: list[str]
    glossary: list[tuple[str, str]]
    index_terms: list[str]
    assets: dict[str, BookAsset]
    labels: dict[str, str] = field(default_factory=dict)  # block id -> "Figure 2.1"
    warnings: list[dict[str, str]] = field(default_factory=list)
    identifier: str = ""
    modified: str = ""

    def warn(self, code: str, message: str) -> None:
        self.warnings.append({"code": code, "message": message})

    def matter(self, kind: str) -> MatterItem | None:
        return next((m for m in self.front + self.back if m.kind == kind), None)

    def cite_label(self, item: dict[str, Any]) -> str:
        e = self.bibliography.get(item["key"])
        loc = f", {item['locator']}" if item.get("locator") else ""
        if e is None:
            return f"{item['key']}{loc}"
        if e.authors and e.year:
            names = e.authors[0].split(",")[0].split()[-1] if e.authors[0] else e.title
            more = (
                " et al." if len(e.authors) > 2 else (f" and {e.authors[1].split()[-1]}" if len(e.authors) == 2 else "")
            )
            return f"{names}{more} {e.year}{loc}"
        short = e.title if len(e.title) <= 40 else e.title[:39] + "…"
        return f"{short}{loc}"


def _walk(blocks: list[Block]) -> list[Block]:
    out: list[Block] = []
    for b in blocks:
        out.append(b)
        for key in ("blocks",):
            if isinstance(b.get(key), list):
                out += _walk(b[key])
        if b.get("type") == "list":
            for it in b["items"]:
                out += _walk(it["blocks"])
    return out


def _inlines(doc: dict[str, Any]) -> list[dict[str, Any]]:
    return list(bookmd.iter_all_inlines(doc))


def assemble(ctx: AppContext, s: Session, project: Project, profile: dict[str, Any]) -> Book:
    template_key = profile.get("template") or "nonfiction"
    template = dict(TEMPLATES[template_key])
    matter_cfg = profile.get("matter") or default_matter(template_key)
    copyright_cfg = profile.get("copyright") or {}
    chapters: list[BookChapter] = []
    number = 0
    latest = ""
    for chapter, depth in tree_order(active_chapters(s, project.id)):
        head = s.get(ChapterRevision, chapter.head_revision_id) if chapter.head_revision_id else None
        doc = documents.bdm_of(ctx, head) if head is not None else None
        if depth == 0 and chapter.kind != "part":
            number += 1
        chapters.append(
            BookChapter(
                id=chapter.id,
                title=chapter.title,
                slug=chapter.slug,
                kind=chapter.kind,
                depth=depth,
                number=number if depth == 0 and chapter.kind != "part" else None,
                source_md=head.source_md if head else "",
                doc=doc,
                revision_no=chapter.head_revision_no,
            )
        )
        if head is not None and head.created_at > latest:
            latest = head.created_at
    book = Book(
        project_id=project.id,
        title=project.title,
        subtitle=project.subtitle,
        author=project.author_name,
        language=project.language or "en",
        template_key=template_key,
        template=template,
        front=[],
        chapters=chapters,
        back=[],
        copyright=copyright_cfg,
        bibliography={},
        cited_keys=[],
        glossary=[],
        index_terms=[t.strip() for t in profile.get("index_terms") or [] if t.strip()],
        assets={},
        identifier=f"urn:pbs:{project.id}",
        modified=(latest or project.updated_at)[:19] + "Z",
    )
    isbn = (copyright_cfg.get("isbn") or "").strip()
    if isbn:
        if isbn_valid(isbn):
            book.identifier = "urn:isbn:" + re.sub(r"[\s-]", "", isbn)
        else:
            book.warn("isbn_invalid", f"The ISBN “{isbn}” has an invalid check digit; it was left out.")
            book.copyright = {**copyright_cfg, "isbn": ""}
    if not book.author:
        book.warn("no_author", "No author name is set in the book details.")
    for ch in chapters:
        if ch.doc is None:
            book.warn("empty_chapter", f"“{ch.title}” has no saved text; only its title is exported.")
    _assets(ctx, s, book)
    _number(book)
    _citations(s, book)
    _glossary(s, book, matter_cfg)
    for cfg in matter_cfg:
        kind = cfg.get("kind")
        if kind not in MATTER_KINDS or not cfg.get("enabled"):
            continue
        position, default_title, generated = MATTER_KINDS[kind]
        body = (cfg.get("body_md") or "").strip()
        item = MatterItem(kind, position, (cfg.get("title") or default_title).strip(), body, generated)
        if not generated and kind not in ("glossary",) and not body:
            book.warn("empty_matter", f"“{item.title}” is turned on but has no text, so it was left out.")
            continue
        if kind == "copyright" and not any(
            (copyright_cfg.get(k) or "").strip() for k in ("holder", "year", "notice_md", "isbn", "edition")
        ):
            book.warn(
                "copyright_empty",
                "The copyright page is on but you have not entered a notice, holder, year or ISBN. PBS does not "
                "write legal statements for you, so the page was left out.",
            )
            continue
        if kind == "bibliography" and not book.cited_keys:
            continue
        if kind == "glossary" and not book.glossary:
            book.warn("empty_matter", "The glossary is turned on but has no entries, so it was left out.")
            continue
        if kind == "index" and not book.index_terms:
            book.warn("empty_matter", "The index is turned on but has no index terms, so it was left out.")
            continue
        if body:
            item.doc = bookmd.parse(body, chapter_id=f"matter-{kind}", new_id=ctx.ids.new).doc
        (book.front if position == "front" else book.back).append(item)
    return book


def _assets(ctx: AppContext, s: Session, book: Book) -> None:
    from pbs_core.services.exports import _asset_bytes

    rows = {a.short_hash: a for a in s.scalars(select(Asset).where(Asset.project_id == book.project_id))}
    used: list[str] = []
    for ch in book.chapters:
        if ch.doc is None:
            continue
        for b in _walk(ch.doc.get("blocks", [])):
            if b.get("type") == "figure" and str(b.get("src", "")).startswith("asset:"):
                used.append(b["src"][6:])
        for n in _inlines(ch.doc):
            if n.get("t") == "image" and str(n.get("src", "")).startswith("asset:"):
                used.append(n["src"][6:])
    for h in dict.fromkeys(used):
        a = rows.get(h)
        if a is None:
            book.warn("missing_asset", f"Image asset:{h} is missing from this project.")
            continue
        book.assets[h] = BookAsset(h, a.mime, _asset_bytes(ctx, a), a.width_px, a.height_px, a.original_name or h)


def _number(book: Book) -> None:
    numbered = book.template["number_captions"]
    for ch in book.chapters:
        if ch.doc is None:
            continue
        counts = {"figure": 0, "table": 0, "code": 0}
        prefix = f"{ch.number}." if ch.number else ""
        for b in _walk(ch.doc.get("blocks", [])):
            t = b.get("type")
            captioned = (
                (t == "figure" and b.get("caption"))
                or (t == "table" and b.get("caption"))
                or (t == "code" and b.get("attrs", {}).get("kv", {}).get("caption"))
            )
            if not captioned or not numbered:
                continue
            kind = str(t)
            counts[kind] += 1
            word = {"figure": "Figure", "table": "Table", "code": "Listing"}[kind]
            book.labels[b["id"]] = f"{word} {prefix}{counts[kind]}"


def _citations(s: Session, book: Book) -> None:
    keys: list[str] = []
    for ch in book.chapters:
        if ch.doc is None:
            continue
        for n in _inlines(ch.doc):
            if n.get("t") == "cite":
                keys += [i["key"] for i in n["items"]]
    book.cited_keys = list(dict.fromkeys(keys))
    if not book.cited_keys:
        return
    libs = retrieval.library_ids(s, book.project_id)
    rows = (
        s.scalars(select(Source).where(Source.library_id.in_(libs), Source.citation_key.in_(book.cited_keys))).all()
        if libs
        else []
    )
    for r in rows:
        book.bibliography[r.citation_key] = BibEntry(
            key=r.citation_key,
            authors=[str(a) for a in json.loads(r.authors_json or "[]")],
            year=str(r.year) if r.year else None,
            title=r.title,
            publisher=r.publisher,
            url=r.url,
            doi=r.doi,
        )
    for k in book.cited_keys:
        if k not in book.bibliography:
            book.warn(
                "unknown_citation",
                f"Citation key “{k}” matches no source in this book's libraries; it is printed as the key.",
            )


def _glossary(s: Session, book: Book, matter_cfg: list[dict[str, Any]]) -> None:
    cfg = next((m for m in matter_cfg if m.get("kind") == "glossary"), None)
    if not cfg or not cfg.get("enabled"):
        return
    entries: dict[str, str] = {}
    for line in (cfg.get("body_md") or "").splitlines():
        m = re.match(r"^\s*[-*]?\s*\*{0,2}([^:*]+?)\*{0,2}\s*:\s*(.+)$", line)
        if m:
            entries[m.group(1).strip()] = m.group(2).strip()
    if cfg.get("include_story_bible_terms", True):
        for f in s.scalars(
            select(ContinuityFact).where(
                ContinuityFact.project_id == book.project_id,
                ContinuityFact.kind == "term",
                ContinuityFact.status == "confirmed",
            )
        ):
            entries.setdefault(f.name, f.value)
    book.glossary = sorted(entries.items(), key=lambda kv: kv[0].lower())
    cfg_body = cfg.get("body_md") or ""
    if cfg_body.strip() and not entries:
        book.warn("glossary_format", "Glossary text has no “term: definition” lines; write one entry per line.")


def chapter_order_check(book: Book) -> list[str]:
    return [c.title for c in book.chapters]


def index_hits(book: Book) -> dict[str, list[str]]:
    """Index term -> chapter ids where it appears (reflowable formats link to chapters)."""
    out: dict[str, list[str]] = {}
    for term in book.index_terms:
        rx = re.compile(rf"\b{re.escape(term)}\b", re.IGNORECASE)
        out[term] = [c.id for c in book.chapters if rx.search(c.source_md)]
    return out


def chapter_by_id(book: Book, cid: str) -> BookChapter | None:
    return next((c for c in book.chapters if c.id == cid), None)


def project_language(s: Session, project_id: str) -> str:
    p = s.get(Project, project_id)
    return p.language if p else "en"


def chapter_rows(s: Session, project_id: str) -> list[Chapter]:
    return list(active_chapters(s, project_id))
