def default_matter(template: str) -> list[dict[str, Any]]:
    on = set(DEFAULT_MATTER.get(template, []))
    return [
        {"kind": k, "enabled": k in on, "title": title, "body_md": ""}
        for k, (_, title, _) in MATTER_KINDS.items()
        if k != "appendix"
    ]


def isbn_valid(isbn: str) -> bool:
    d = re.sub(r"[\s-]", "", isbn)
    if re.fullmatch(r"\d{13}", d):
        return sum(int(c) * (1 if i % 2 == 0 else 3) for i, c in enumerate(d)) % 10 == 0
    if re.fullmatch(r"\d{9}[\dXx]", d):
        total = sum((10 - i) * (10 if c in "Xx" else int(c)) for i, c in enumerate(d))
        return total % 11 == 0
    return False


