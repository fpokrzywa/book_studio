"""Assemble a book for export: interior template, front and back matter, chapters, numbering, citations.

Every writer (Markdown, HTML, EPUB, DOCX, Typst/PDF) works from the same assembled Book, so chapter
order, figure/table/listing numbers, citation labels and matter are identical in every format.

Nothing is invented: the copyright page shows only what the author entered (no generated notices,
no ISBN), and an enabled text item with no text is left out with a warning instead of a placeholder.
"""

